-- Box-score stats, one row per player, week and season type (REG, POST), from nflverse's
-- weekly player stats. Rows without a player_id (about 21 a season, credited to "Team") aren't
-- a player, so they're left out.
select
    player_id || '-' || season || '-' || week || '-' || season_type as player_week_key,
    season,
    week,
    season_type,
    game_id,
    player_id,
    player_display_name as player_name,
    position,
    position_group,
    team,
    opponent_team,
    completions,
    attempts,
    passing_yards,
    passing_tds,
    passing_interceptions,
    sacks_suffered,
    carries,
    rushing_yards,
    rushing_tds,
    receptions,
    targets,
    receiving_yards,
    receiving_tds,
    coalesce(rushing_fumbles_lost, 0) + coalesce(receiving_fumbles_lost, 0) + coalesce(sack_fumbles_lost, 0) as fumbles_lost,
    def_tackles_solo,
    def_tackle_assists,
    def_tackles_for_loss,
    def_sacks,
    def_qb_hits,
    def_interceptions,
    def_pass_defended,
    def_fumbles_forced,
    def_tds,
    fg_made,
    fg_att,
    fg_long,
    pat_made,
    pat_att,
    special_teams_tds
from {{ source('raw', 'player_stats') }}
where player_id is not null
